import assert from 'node:assert/strict';
import { createReleaseCandidate } from '../src/lib/releaseCandidate';
import { createPostPublishObservation } from '../src/lib/postPublishFeedback';
import { comparePostPublishObservations, createPostPublishExperimentReview, experimentReviewIsCurrent } from '../src/lib/postPublishExperiment';
import { scenePlanToSnapshot, type ScenePlan } from '../src/lib/agent/scenePlan';

const plan: ScenePlan = { projectName: '同主题版本实验', scenes: [{ id: 's1', duration: 20, blocks: [{ type: 'text', content: '观点', duration: 20 }] }] };
const snapshot = scenePlanToSnapshot(plan);
snapshot.director = { objective: '解释同一个问题', audience: '创作者', thesis: '同一个核心表达', contentType: 'knowledge', tone: '克制', pacing: 'balanced', emotionArc: '', endingAction: '', visualRules: '', scenes: {}, updatedAt: 'v1' };
const leftRC = createReleaseCandidate(snapshot, [], new Date('2026-09-18T00:00:00.000Z'));
const rightSnapshot = structuredClone(snapshot);
rightSnapshot.blocks[0].start = 0.2;
const rightRC = createReleaseCandidate(rightSnapshot, [leftRC], new Date('2026-09-18T01:00:00.000Z'));
leftRC.render = { outputPath: 'left.mp4', reportPath: 'left.json', sha256: 'sha-left', renderedAt: '2026-09-18T02:00:00.000Z' };
rightRC.render = { outputPath: 'right.mp4', reportPath: 'right.json', sha256: 'sha-right', renderedAt: '2026-09-18T02:10:00.000Z' };
const candidates = [leftRC, rightRC];
const now = new Date('2026-09-21T00:00:00.000Z');
const common = { source: { kind: 'manual-entry' as const, platform: 'B站', accountLabel: '账号 A', postUrl: '' }, publishedAt: '2026-09-18T08:00:00.000Z', observedAt: '2026-09-19T08:00:00.000Z' };
const left = createPostPublishObservation({ ...common, rcId: leftRC.id, source: { ...common.source, postUrl: 'BV-left' }, metrics: { views: 1000, averageWatchSeconds: 7, completionRate: 30, retention: [{ second: 3, rate: 60 }], comments: { total: 20, questions: 6 } } }, candidates, now);
const right = createPostPublishObservation({ ...common, rcId: rightRC.id, source: { ...common.source, postUrl: 'BV-right' }, metrics: { views: 1200, averageWatchSeconds: 9, completionRate: 40, retention: [{ second: 3.2, rate: 70 }], comments: { total: 25, questions: 5 } } }, candidates, now);
const before = JSON.stringify({ left, right, candidates });
const comparison = comparePostPublishObservations(left, right, candidates, now);
assert.equal(comparison.status, 'comparable');
assert.equal(comparison.blockers.length, 0);
assert.equal(comparison.facts.left.topic, comparison.facts.right.topic);
assert.equal(comparison.metrics.find((item) => item.key === 'completion')?.delta, 10);
assert.equal(comparison.metrics.find((item) => item.key === 'retention-3')?.delta, 10);
assert.equal(JSON.stringify({ left, right, candidates }), before, 'comparison is read-only');

const later = { ...right, id: 'later', publishedAt: '2026-09-19T12:00:00.000Z', observedAt: '2026-09-20T13:00:00.000Z', windowHours: 25, metrics: { ...right.metrics, views: 3000 } };
const limited = comparePostPublishObservations(left, later, candidates, now);
assert.equal(limited.status, 'limited');
assert(limited.warnings.some((item) => item.includes('发布时间')));
assert(limited.warnings.some((item) => item.includes('样本量')));

const platformMismatch = comparePostPublishObservations(left, { ...right, source: { ...right.source, platform: '抖音' } }, candidates, now);
assert(platformMismatch.blockers.some((item) => item.includes('平台')));
const accountMismatch = comparePostPublishObservations(left, { ...right, source: { ...right.source, accountLabel: '账号 B' } }, candidates, now);
assert(accountMismatch.blockers.some((item) => item.includes('账号')));
const windowMismatch = comparePostPublishObservations(left, { ...right, windowHours: 80 }, candidates, now);
assert(windowMismatch.blockers.some((item) => item.includes('观测窗口')));
const topicRC = structuredClone(rightRC);
topicRC.snapshot.director!.thesis = '另一个主题';
const topicMismatch = comparePostPublishObservations(left, right, [leftRC, topicRC], now);
assert(topicMismatch.blockers.some((item) => item.includes('核心表达')));
assert(comparePostPublishObservations(left, left, candidates, now).blockers.some((item) => item.includes('同一个 RC')));
assert(comparePostPublishObservations(left, right, [leftRC], now).blockers.some((item) => item.includes('无法验证')));
assert(comparePostPublishObservations(left, { ...right, metrics: { retention: [] } }, candidates, now).blockers.some((item) => item.includes('指标')));
const sameHashRC = { ...rightRC, render: { ...rightRC.render, sha256: 'sha-left' } };
const sameHashObservation = { ...right, renderSha256: 'sha-left' };
assert(comparePostPublishObservations(left, sameHashObservation, [leftRC, sameHashRC], now).blockers.some((item) => item.includes('哈希相同')));

assert.throws(() => createPostPublishExperimentReview(platformMismatch, '不能比较', true), /阻断/);
assert.throws(() => createPostPublishExperimentReview(comparison, '描述性提升', false), /因果/);
assert.throws(() => createPostPublishExperimentReview(comparison, '', true), /结论/);
const review = createPostPublishExperimentReview(comparison, '在相同条件下，对照版本的描述性指标更高；仍需重复实验。', true, [], now);
assert(experimentReviewIsCurrent(review, [left, right], candidates));
assert(!experimentReviewIsCurrent(review, [left, right], [leftRC, { ...rightRC, render: { ...rightRC.render, sha256: 'changed' } }]));
assert.throws(() => createPostPublishExperimentReview(comparePostPublishObservations(right, left, candidates, now), '反向重复', true, [review], now), /已经保存/);
assert.equal(JSON.stringify({ left, right, candidates }), before, 'review does not rewrite evidence or RCs');
console.log('Post-publish experiment checks passed: comparable gates, explicit confounders, descriptive deltas, non-causal confirmation, duplicate and credential guards.');
